# 2. Initialize TimeSeriesSplit
tscv = TimeSeriesSplit(n_splits=5)
mae_scores = []

print(f'Starting Rolling Forecast Evaluation with {tscv.n_splits} splits...\n')

# 3. Iterate through splits
for i, (train_index, test_index) in enumerate(tscv.split(X_rolling)):
    X_train_fold, X_test_fold = X_rolling.iloc[train_index], X_rolling.iloc[test_index]
    y_train_fold, y_test_fold = y_rolling.iloc[train_index], y_rolling.iloc[test_index]

    # Initialize and train XGBoost
    xgb_model = XGBRegressor(n_estimators=100, learning_rate=0.1, max_depth=5, random_state=42)
    xgb_model.fit(X_train_fold, y_train_fold)

    # Predict and evaluate
    y_pred_fold = xgb_model.predict(X_test_fold)
    fold_mae = mean_absolute_error(y_test_fold, y_pred_fold)
    mae_scores.append(fold_mae)

    print(f'Fold {i+1} MAE: {fold_mae:.4f}')

